// den blocks as patchable nodes. Port ids equal den's argument/field names so
// the descriptor maps 1:1 onto each block's tick signature; ranges follow the
// clamps documented in den's source (src/*.ts). Bounds here are the AudioParam
// bounds used when an input is left unconnected.
import type { ConfigDef, NodeDef, PortDef } from '../core/catalog.ts';

const audio = (id: string, label?: string, extra: Partial<PortDef> = {}): PortDef => ({
  id,
  type: 'signal',
  role: 'audio',
  label,
  ...extra,
});
const ctl = (
  id: string,
  def: number,
  min: number,
  max: number,
  extra: Partial<PortDef> = {},
): PortDef => ({ id, type: 'signal', role: 'control', default: def, min, max, ...extra });
const hz = (id: string, def: number, min = 0, max = 21600, extra: Partial<PortDef> = {}) =>
  ctl(id, def, min, max, {
    unit: 'Hz',
    scale: 'log',
    uiMin: Math.max(min, 20),
    uiMax: Math.min(max, 20000),
    ...extra,
  });
const sec = (id: string, def: number, max = 30, extra: Partial<PortDef> = {}) =>
  ctl(id, def, 0, max, { unit: 's', scale: 'log', uiMax: Math.min(max, 5), ...extra });
const unit = (id: string, def: number, extra: Partial<PortDef> = {}) =>
  ctl(id, def, 0, 1, { unit: 'mix', ...extra });
const toggle = (id: string, doc?: string): PortDef => ({ id, type: 'gate', default: false, doc });
const reset = (
  doc = 'Restarts phase/state. In a voice: on a new note or a stolen voice; globally: on panic.',
): PortDef => ({ id: 'reset', type: 'gate', binding: 'reset', doc });
const clear = (): PortDef => ({
  id: 'reset',
  type: 'gate',
  binding: 'clear',
  doc: 'Hard reset. In a voice: only when the voice is stolen/cleared; globally: on panic.',
});
const out = (id = 'out', label?: string): PortDef => ({ id, type: 'signal', label });
const enumConfig = (
  id: string,
  options: readonly string[],
  def: string,
  doc?: string,
): ConfigDef => ({ id, kind: 'enum', options, default: def, doc });
const num = (
  id: string,
  def: number,
  min: number,
  max: number,
  extra: Partial<ConfigDef> = {},
): ConfigDef => ({ id, kind: 'number', default: def, min, max, ...extra });

const stereoIn = [
  audio('left', 'L'),
  audio('right', 'R', { fallback: 'left', doc: 'Unconnected: uses left.' }),
];
const stereoOut = [out('left', 'L'), out('right', 'R')];

const delayBytes = (seconds: number, sampleRate: number, heads = 2) =>
  heads * 4 * (Math.ceil(seconds * sampleRate) + 2);

